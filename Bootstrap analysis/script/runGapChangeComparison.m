function data = readPairedLongData(fileName, sheetName, timeColumn, ...
    MColumn, EColumn, groupLabel)
% Read one long-format group and preserve complete within-row M/E pairs.

    raw = readmatrix(fileName, 'Sheet', sheetName);
    requiredColumn = max([timeColumn, MColumn, EColumn]);
    if size(raw, 2) < requiredColumn
        error('fig5hi:MissingColumn', ...
            '%s has %d columns but column %d is required.', ...
            groupLabel, size(raw, 2), requiredColumn);
    end

    timeRaw = raw(:, timeColumn);
    MRaw = raw(:, MColumn);
    ERaw = raw(:, EColumn);
    time = unique(timeRaw(isfinite(timeRaw)));
    nTime = numel(time);
    if nTime < 2
        error('fig5hi:InsufficientTimePoints', ...
            '%s has fewer than two finite sampled times.', groupLabel);
    end

    M = cell(1, nTime);
    E = cell(1, nTime);
    nPairs = NaN(nTime, 1);
    mean_M = NaN(nTime, 1);
    sd_M = NaN(nTime, 1);
    mean_E = NaN(nTime, 1);
    sd_E = NaN(nTime, 1);
    pairedCorrelation = NaN(nTime, 1);

    for j = 1:nTime
        rowAtTime = timeRaw == time(j);
        Mj = MRaw(rowAtTime);
        Ej = ERaw(rowAtTime);
        completePair = isfinite(Mj) & isfinite(Ej);

        if any(xor(isfinite(Mj), isfinite(Ej)))
            warning('fig5hi:IncompletePair', ...
                ['%s time %.4g contains incomplete M/E rows. These rows ' ...
                 'are excluded so all bootstrap observations stay paired.'], ...
                groupLabel, time(j));
        end

        Mj = Mj(completePair);
        Ej = Ej(completePair);
        Mj = Mj(:);
        Ej = Ej(:);
        if isempty(Mj)
            error('fig5hi:NoPairsAtTime', ...
                '%s has no complete M/E pairs at time %.4g.', ...
                groupLabel, time(j));
        end

        M{j} = Mj;
        E{j} = Ej;
        nPairs(j) = numel(Mj);
        mean_M(j) = mean(Mj);
        sd_M(j) = std(Mj);
        mean_E(j) = mean(Ej);
        sd_E(j) = std(Ej);

        if numel(Mj) > 2 && std(Mj) > 0 && std(Ej) > 0
            correlationMatrix = corrcoef(Mj, Ej);
            pairedCorrelation(j) = correlationMatrix(1, 2);
        end
    end

    [~, hardIndex_M] = max(mean_M);
    [~, hardIndex_E] = max(mean_E);

    data = struct();
    data.label = groupLabel;
    data.fileName = fileName;
    data.time = time(:);
    data.M = M;
    data.E = E;
    data.nPairs = nPairs;
    data.mean_M = mean_M;
    data.mean_E = mean_E;
    data.hardPeak_M = time(hardIndex_M);
    data.hardPeak_E = time(hardIndex_E);
    data.hardPhaseGap_E_minus_M = data.hardPeak_E - data.hardPeak_M;
    data.timepointTable = table(time(:), nPairs, mean_M, sd_M, ...
        mean_E, sd_E, pairedCorrelation, 'VariableNames', ...
        {'Time_h', 'N_pairs', 'Mean_M', 'SD_M', 'Mean_E', 'SD_E', ...
         'PairedCorrelation_M_E'});
end

function printPairedDataSummary(data)
    fprintf('%-8s %-8s %-12s %-12s %-12s\n', ...
        'Time', 'nPair', 'Mean M', 'Mean E', 'Pair r');
    for j = 1:numel(data.time)
        fprintf('%-8.4g %-8d %-12.3f %-12.3f %-12.3f\n', ...
            data.time(j), data.nPairs(j), data.mean_M(j), ...
            data.mean_E(j), ...
            data.timepointTable.PairedCorrelation_M_E(j));
    end
    fprintf('Observed hard peaks: M=%.4g h, E=%.4g h, E-M=%.4g h\n', ...
        data.hardPeak_M, data.hardPeak_E, ...
        data.hardPhaseGap_E_minus_M);
end

function [covarianceValue, correlationValue] = safeCovCorr(x, y)
    valid = isfinite(x) & isfinite(y);
    x = x(valid);
    y = y(valid);
    covarianceValue = NaN;
    correlationValue = NaN;
    if numel(x) < 2
        return;
    end

    covarianceMatrix = cov(x, y);
    covarianceValue = covarianceMatrix(1, 2);
    if std(x) > 0 && std(y) > 0
        correlationMatrix = corrcoef(x, y);
        correlationValue = correlationMatrix(1, 2);
    end
end
