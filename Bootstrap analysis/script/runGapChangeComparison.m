function publicResult = runGapChangeComparison(cfg)
% Shared publication pipeline; settings are supplied by the figure entry script.
figureCleanup = bootstrapFigureContext(cfg); %#ok<NASGU>
folderPath = cfg.outputDir;
filePath = cfg.inputFile;
smokeTestMode = false;
controlPath = cfg.controlPath;
analysisMode = cfg.analysisMode;
conditionLabel = cfg.conditionLabel;
controlLabel = cfg.controlLabel;
conditionColor = cfg.conditionColor;
controlColor = cfg.controlColor;
dataSheet = cfg.dataSheet;
timeColumn = cfg.timeColumn;
MColumn = cfg.MColumn;
EColumn = cfg.EColumn;
nInner = cfg.nInner;
nOuter = cfg.nOuter;
delta0 = cfg.delta0;
alpha = cfg.alpha;
rngSeed = cfg.rngSeed;
mainFigureBinWidth = cfg.mainFigureBinWidth;
outputExcel = fullfile(folderPath, cfg.outputStem + "_results.xlsx");
outputMAT = fullfile(folderPath, cfg.outputStem + "_results.mat");
outputMainSVG = fullfile(folderPath, cfg.outputStem + ".svg");
outputDiagnosticSVG = fullfile(folderPath, cfg.outputStem + "_diagnostics.svg");

conditionData = readPairedLongData(filePath, dataSheet, timeColumn, ...
    MColumn, EColumn, conditionLabel);
controlData = readPairedLongData(controlPath, cfg.controlSheet, timeColumn, ...
    MColumn, EColumn, controlLabel);

fprintf('\n============================================================\n');
fprintf('Paired input-data summary: %s\n', conditionLabel);
fprintf('============================================================\n');
printPairedDataSummary(conditionData);
fprintf('\n============================================================\n');
fprintf('Paired input-data summary: %s\n', controlLabel);
fprintf('============================================================\n');
printPairedDataSummary(controlData);

sameTimeGrid = isequal(conditionData.time, controlData.time);
if ~sameTimeGrid
    warning('fig5hi:DifferentTimeGrids', ...
        ['Condition and control use different sampled-time grids. Each ' ...
         'bagged estimator is retained on its own observed grid; review ' ...
         'peak-location probabilities to verify comparable peak coverage.']);
end

%% ========================================================================
% PART 2. Paired inner/outer bagging and MET for phase-gap change
% ========================================================================
% Group-specific phase gap:
%   G_condition = Tbag_E_condition - Tbag_M_condition
%   G_control   = Tbag_E_control   - Tbag_M_control
%
% Primary contrast (change in phase gap):
%   Gamma = G_condition - G_control
%
% Wald-type minimum-effect test for the interval null:
%   H0: |Gamma| <= delta0
%   H1: |Gamma| >  delta0

fprintf('\nComputing original-data inner bagging (nInner=%d)...\n', ...
    nInner);
rng(rngSeed + 1, 'twister');
[Tbag_M_condition, Tbag_E_condition, innerPeakTimes_M_condition, ...
    innerPeakTimes_E_condition, P_M_condition, P_E_condition] = ...
    computePairedBaggedPeaks(conditionData.M, conditionData.E, ...
    conditionData.time, nInner);

rng(rngSeed + 2, 'twister');
[Tbag_M_control, Tbag_E_control, innerPeakTimes_M_control, ...
    innerPeakTimes_E_control, P_M_control, P_E_control] = ...
    computePairedBaggedPeaks(controlData.M, controlData.E, ...
    controlData.time, nInner);

phaseGap_condition = Tbag_E_condition - Tbag_M_condition;
phaseGap_control = Tbag_E_control - Tbag_M_control;
phaseGapChange = phaseGap_condition - phaseGap_control;

% Each outer replicate independently resamples the condition group and the
% control group. Within each group, M/E row pairing remains intact. The two
% independently generated group estimates are then subtracted to obtain one
% bootstrap replicate of Gamma.
outerTbag_M_condition = NaN(nOuter, 1);
outerTbag_E_condition = NaN(nOuter, 1);
outerTbag_M_control = NaN(nOuter, 1);
outerTbag_E_control = NaN(nOuter, 1);

rng(rngSeed + 3, 'twister');
outerStart = tic;
progressStep = max(1, floor(nOuter / 20));
fprintf(['Running independent-group, paired-within-group outer bootstrap ' ...
    '(nOuter=%d)...\n'], nOuter);

for b = 1:nOuter
    [outerCondition_M, outerCondition_E] = bootstrapPairedDataset( ...
        conditionData.M, conditionData.E);
    [outerTbag_M_condition(b), outerTbag_E_condition(b)] = ...
        computePairedBaggedPeaks(outerCondition_M, outerCondition_E, ...
        conditionData.time, nInner);

    [outerControl_M, outerControl_E] = bootstrapPairedDataset( ...
        controlData.M, controlData.E);
    [outerTbag_M_control(b), outerTbag_E_control(b)] = ...
        computePairedBaggedPeaks(outerControl_M, outerControl_E, ...
        controlData.time, nInner);

    if mod(b, progressStep) == 0 || b == nOuter
        fprintf('  outer bootstrap: %d/%d complete\n', b, nOuter);
    end
end
outerElapsedSeconds = toc(outerStart);

outerPhaseGap_condition = ...
    outerTbag_E_condition - outerTbag_M_condition;
outerPhaseGap_control = outerTbag_E_control - outerTbag_M_control;
outerPhaseGapChange = outerPhaseGap_condition - outerPhaseGap_control;

validCondition = isfinite(outerTbag_M_condition) & ...
    isfinite(outerTbag_E_condition) & isfinite(outerPhaseGap_condition);
validControl = isfinite(outerTbag_M_control) & ...
    isfinite(outerTbag_E_control) & isfinite(outerPhaseGap_control);
validContrast = validCondition & validControl & ...
    isfinite(outerPhaseGapChange);

if sum(validContrast) < 2
    error('fig5hi:InsufficientOuterReplicates', ...
        'Fewer than two valid outer phase-gap-change replicates.');
end

% Sampling uncertainty: these are outer-bootstrap SD/SE values. They are
% not divided by sqrt(nOuter); nOuter controls Monte Carlo precision only.
outerSD_M_condition = std(outerTbag_M_condition(validCondition));
outerSD_E_condition = std(outerTbag_E_condition(validCondition));
phaseGapSE_condition = std(outerPhaseGap_condition(validCondition));
outerSD_M_control = std(outerTbag_M_control(validControl));
outerSD_E_control = std(outerTbag_E_control(validControl));
phaseGapSE_control = std(outerPhaseGap_control(validControl));
phaseGapChangeSE = std(outerPhaseGapChange(validContrast));

CI95_M_condition = prctile(outerTbag_M_condition(validCondition), ...
    [2.5 97.5]);
CI95_E_condition = prctile(outerTbag_E_condition(validCondition), ...
    [2.5 97.5]);
CI95_gap_condition = prctile(outerPhaseGap_condition(validCondition), ...
    [2.5 97.5]);
CI95_M_control = prctile(outerTbag_M_control(validControl), [2.5 97.5]);
CI95_E_control = prctile(outerTbag_E_control(validControl), [2.5 97.5]);
CI95_gap_control = prctile(outerPhaseGap_control(validControl), ...
    [2.5 97.5]);
CI95_gapChange = prctile(outerPhaseGapChange(validContrast), [2.5 97.5]);

[MET_z, MET_p, MET_z_near, MET_z_far, boundaryZ_lower, ...
    boundaryZ_upper] = computeWaldMET(phaseGapChange, ...
    phaseGapChangeSE, delta0);

thresholdExcess = abs(phaseGapChange) - delta0;
standardizedEffect = phaseGapChange / phaseGapChangeSE;
standardizedThresholdExcess = thresholdExcess / phaseGapChangeSE;
bootstrapSupport = mean(abs(outerPhaseGapChange(validContrast)) > delta0);

[stability_M_condition, entropy_M_condition] = ...
    computePeakStability(P_M_condition);
[stability_E_condition, entropy_E_condition] = ...
    computePeakStability(P_E_condition);
[stability_M_control, entropy_M_control] = ...
    computePeakStability(P_M_control);
[stability_E_control, entropy_E_control] = ...
    computePeakStability(P_E_control);

confidence_M_condition = max(P_M_condition);
confidence_E_condition = max(P_E_condition);
confidence_M_control = max(P_M_control);
confidence_E_control = max(P_E_control);

% Numerical-integration diagnostics only. These sqrt terms quantify Monte
% Carlo precision and are never used as experimental sampling SEs.
innerMCSE_M_condition = std(innerPeakTimes_M_condition, 'omitnan') / ...
    sqrt(sum(isfinite(innerPeakTimes_M_condition)));
innerMCSE_E_condition = std(innerPeakTimes_E_condition, 'omitnan') / ...
    sqrt(sum(isfinite(innerPeakTimes_E_condition)));
innerMCSE_M_control = std(innerPeakTimes_M_control, 'omitnan') / ...
    sqrt(sum(isfinite(innerPeakTimes_M_control)));
innerMCSE_E_control = std(innerPeakTimes_E_control, 'omitnan') / ...
    sqrt(sum(isfinite(innerPeakTimes_E_control)));
outerSEMonteCarloErrorApprox = phaseGapChangeSE / ...
    sqrt(2 * max(sum(validContrast) - 1, 1));

[outerCov_condition, outerCorr_condition] = safeCovCorr( ...
    outerTbag_M_condition(validCondition), ...
    outerTbag_E_condition(validCondition));
[outerCov_control, outerCorr_control] = safeCovCorr( ...
    outerTbag_M_control(validControl), ...
    outerTbag_E_control(validControl));

% Shape diagnostics refer to the primary outer phase-gap-change
% distribution used to estimate the MET standard error.
contrastValues = outerPhaseGapChange(validContrast);
outerSkewness = skewness(contrastValues, 0);
outerKurtosis = kurtosis(contrastValues, 0); % normal distribution = 3
if isfinite(outerKurtosis) && outerKurtosis > 0
    outerBimodalityCoefficient = ...
        (outerSkewness ^ 2 + 1) / outerKurtosis;
else
    outerBimodalityCoefficient = NaN;
end

if numel(contrastValues) >= 8 && phaseGapChangeSE > 0
    [JB_reject, JB_p] = jbtest(contrastValues, alpha);
else
    JB_reject = NaN;
    JB_p = NaN;
end

stronglyNonNormal = abs(outerSkewness) > 1 || ...
    outerKurtosis > 5 || ...
    (isfinite(outerBimodalityCoefficient) && ...
     outerBimodalityCoefficient > 5 / 9);

if stronglyNonNormal
    warning('fig5hi:StronglyNonNormalOuterContrast', ...
        ['Outer bootstrap phase-gap-change distribution is strongly ' ...
         'non-normal; consider a studentized-bootstrap / bootstrap-t MET ' ...
         'as a sensitivity analysis. The Wald MET is retained as primary.']);
end

if isfinite(MET_p) && MET_p < alpha
    MET_decision = "Reject H0: absolute phase-gap change exceeds delta0";
else
    MET_decision = ...
        "Do not reject H0: insufficient evidence of change beyond delta0";
end

% Structured MATLAB outputs.
statsCondition = struct();
statsCondition.label = conditionLabel;
statsCondition.peak_M = Tbag_M_condition;
statsCondition.peak_E = Tbag_E_condition;
statsCondition.phaseGap_E_minus_M = phaseGap_condition;
statsCondition.SE_peak_M = outerSD_M_condition;
statsCondition.SE_peak_E = outerSD_E_condition;
statsCondition.SE_phaseGap = phaseGapSE_condition;
statsCondition.CI95_peak_M = CI95_M_condition;
statsCondition.CI95_peak_E = CI95_E_condition;
statsCondition.CI95_phaseGap = CI95_gap_condition;
statsCondition.peakProbability_M = P_M_condition;
statsCondition.peakProbability_E = P_E_condition;
statsCondition.peakConfidence_M = confidence_M_condition;
statsCondition.peakConfidence_E = confidence_E_condition;
statsCondition.peakStability_M = stability_M_condition;
statsCondition.peakStability_E = stability_E_condition;
statsCondition.outerCorrelation_M_E = outerCorr_condition;

statsControl = struct();
statsControl.label = controlLabel;
statsControl.peak_M = Tbag_M_control;
statsControl.peak_E = Tbag_E_control;
statsControl.phaseGap_E_minus_M = phaseGap_control;
statsControl.SE_peak_M = outerSD_M_control;
statsControl.SE_peak_E = outerSD_E_control;
statsControl.SE_phaseGap = phaseGapSE_control;
statsControl.CI95_peak_M = CI95_M_control;
statsControl.CI95_peak_E = CI95_E_control;
statsControl.CI95_phaseGap = CI95_gap_control;
statsControl.peakProbability_M = P_M_control;
statsControl.peakProbability_E = P_E_control;
statsControl.peakConfidence_M = confidence_M_control;
statsControl.peakConfidence_E = confidence_E_control;
statsControl.peakStability_M = stability_M_control;
statsControl.peakStability_E = stability_E_control;
statsControl.outerCorrelation_M_E = outerCorr_control;

statsContrast = struct();
statsContrast.definition = ...
    '(E-M)_condition - (E-M)_control';
statsContrast.diff = phaseGapChange;
statsContrast.SE = phaseGapChangeSE;
statsContrast.CI95 = CI95_gapChange;
statsContrast.CI_low = CI95_gapChange(1);
statsContrast.CI_high = CI95_gapChange(2);
statsContrast.delta0 = delta0;
statsContrast.thresholdExcess = thresholdExcess;
statsContrast.standardizedEffect = standardizedEffect;
statsContrast.standardizedThresholdExcess = ...
    standardizedThresholdExcess;
statsContrast.MET_z = MET_z;
statsContrast.MET_p = MET_p;
statsContrast.MET_z_near = MET_z_near;
statsContrast.MET_z_far = MET_z_far;
statsContrast.boundaryZ_lower = boundaryZ_lower;
statsContrast.boundaryZ_upper = boundaryZ_upper;
statsContrast.bootstrapSupport = bootstrapSupport;
statsContrast.nInner = nInner;
statsContrast.nOuter = nOuter;
statsContrast.MET_decision = MET_decision;

fprintf('\n====================================================================\n');
fprintf('Bagged phase-gap comparison: %s\n', analysisMode);
fprintf('Phase gap is defined as E-M; positive means E peaks later than M.\n');
fprintf('====================================================================\n');
fprintf('%s phase gap: %.4f +/- %.4f h, 95%% CI [%.4f, %.4f]\n', ...
    conditionLabel, phaseGap_condition, phaseGapSE_condition, ...
    CI95_gap_condition(1), CI95_gap_condition(2));
fprintf('%s phase gap: %.4f +/- %.4f h, 95%% CI [%.4f, %.4f]\n', ...
    controlLabel, phaseGap_control, phaseGapSE_control, ...
    CI95_gap_control(1), CI95_gap_control(2));
fprintf('Gap change (condition-control): %.4f +/- %.4f h\n', ...
    phaseGapChange, phaseGapChangeSE);
fprintf('Gap-change 95%% bootstrap CI: [%.4f, %.4f] h\n', ...
    CI95_gapChange(1), CI95_gapChange(2));
fprintf('Interval null: H0: |gap change| <= %.4f h\n', delta0);
fprintf('Alternative:   H1: |gap change| >  %.4f h\n', delta0);
fprintf('MET Z: %.4f\n', MET_z);
fprintf('MET p-value: %.6g\n', MET_p);
fprintf(['Bootstrap support |gap change| > delta0: %.4f ' ...
    '(descriptive only)\n'], bootstrapSupport);
fprintf('Decision at alpha=%.3f: %s\n', alpha, MET_decision);
fprintf('Outer bootstrap elapsed time: %.1f seconds\n', ...
    outerElapsedSeconds);
fprintf('====================================================================\n');

