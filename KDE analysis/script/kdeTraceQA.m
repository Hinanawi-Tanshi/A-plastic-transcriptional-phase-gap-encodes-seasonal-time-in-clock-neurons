function qa = kdeTraceQA(trace, time, signal)
% KDETRACEQA Report native timestamp issues without changing input order.
finiteTime = time(isfinite(time));
backwards = sum(diff(finiteTime) < 0);
duplicates = numel(finiteTime) - numel(unique(finiteTime));
qa = table(trace.meta.TraceID, trace.meta.Condition, trace.meta.SourceFile, ...
    trace.meta.SourceSheet, numel(time), sum(~isfinite(time)), ...
    sum(isnan(signal)), backwards, duplicates, mean(diff(finiteTime))*60, ...
    'VariableNames', {'TraceID','Condition','SourceFile','SourceSheet', ...
    'NSamples','NonfiniteTimes','MissingSignals','BackwardSteps', ...
    'DuplicateTimes','MeanInterval_min'});
end
